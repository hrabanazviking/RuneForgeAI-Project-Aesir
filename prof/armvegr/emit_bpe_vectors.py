# TEST-ONLY (PRÓF): emit frozen tokenizer vectors as a Mojo test-data module.
# Reads data/armvegr/tokenizer_vectors.json, writes tests/c3_h046_vectors.mojo
# and tests/c3_h047_vectors.mojo (pure data literals, no logic).
import json, sys

def mojo_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")
    return '"' + s + '"'

def emit_bpe(vec, path):
    L = []
    L.append("# GENERATED by prof/armvegr/emit_bpe_vectors.py — frozen H046 test data. Do not edit.")
    L.append("")
    L.append("def bpe_ref_texts() -> List[String]:")
    L.append("    var v = List[String]()")
    for e in vec["bpe_reference"]:
        L.append("    v.append(" + mojo_str(e["text"]) + ")")
    L.append("    return v.copy()")
    L.append("")
    L.append("def bpe_ref_ids() -> List[List[Int]]:")
    L.append("    var v = List[List[Int]]()")
    for e in vec["bpe_reference"]:
        L.append("    v.append([" + ", ".join(str(i) for i in e["ids"]) + "])")
    L.append("    return v.copy()")
    L.append("")
    L.append("def bpe_roundtrip_texts() -> List[String]:")
    L.append("    var v = List[String]()")
    for s in vec["bpe_roundtrip"]:
        L.append("    v.append(" + mojo_str(s) + ")")
    L.append("    return v.copy()")
    L.append("")
    open(path, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", path)

