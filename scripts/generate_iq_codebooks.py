#!/usr/bin/env python3
"""Generate Mojo IQ lookup tables from llama.cpp's gguf-py quants.py."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path


# name -> (entry count, bits per grid digit). IQ2_*/IQ1_S grids pack
# eight 2-bit digits per entry; IQ3_* grids pack four 3-bit digits.
EXPECTED_COUNTS = {
    "IQ2_XXS": (256, 2),
    "IQ1_S": (2048, 2),
    "IQ2_XS": (512, 2),
    "IQ2_S": (1024, 2),
    "IQ3_XXS": (256, 3),
    "IQ3_S": (512, 3),
}

RENDER_ORDER = ("IQ2_XXS", "IQ1_S", "IQ2_XS", "IQ2_S", "IQ3_XXS", "IQ3_S")


def extract_tables(source: Path) -> dict[str, list[int]]:
    tree = ast.parse(source.read_text(encoding="utf-8"), filename=str(source))
    tables: dict[str, list[int]] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef) or node.name not in EXPECTED_COUNTS:
            continue
        for item in node.body:
            if not isinstance(item, ast.Assign):
                continue
            if not any(isinstance(target, ast.Name) and target.id == "grid_hex" for target in item.targets):
                continue
            encoded = ast.literal_eval(item.value)
            if not isinstance(encoded, bytes):
                raise ValueError(f"{node.name}.grid_hex is not a bytes literal")
            raw = bytes.fromhex(encoded.decode("ascii"))
            expected_count, bits = EXPECTED_COUNTS[node.name]
            if len(raw) != expected_count * 2:
                raise ValueError(
                    f"{node.name} grid byte count is {len(raw)}, expected {expected_count * 2}"
                )
            entries: list[int] = []
            if bits == 2:
                # Each byte packs four 2-bit digits, least-significant
                # digit first; a little-endian UInt16 pair is one entry.
                entries = [
                    int.from_bytes(raw[offset : offset + 2], "little")
                    for offset in range(0, len(raw), 2)
                ]
            else:
                # Each byte packs two 3-bit digits (bits 0-2 and 4-6);
                # a byte pair is one entry of four digits, digit j at
                # bit offset 3*j.
                for offset in range(0, len(raw), 2):
                    b0, b1 = raw[offset], raw[offset + 1]
                    digits = (b0 & 7, (b0 >> 4) & 7, b1 & 7, (b1 >> 4) & 7)
                    value = 0
                    for j, digit in enumerate(digits):
                        value |= digit << (3 * j)
                    entries.append(value)
            tables[node.name] = entries
    for name, (expected, _bits) in EXPECTED_COUNTS.items():
        actual = len(tables.get(name, []))
        if actual != expected:
            raise ValueError(f"{name} grid count is {actual}, expected {expected}")
    return tables


def render(tables: dict[str, list[int]]) -> str:
    lines = [
        '"""Generated GGML IQ codebook indices.',
        "",
        "Generated by scripts/generate_iq_codebooks.py from llama.cpp gguf-py.",
        "Each UInt16 packs the entry's grid digits, least-significant digit",
        "first: eight 2-bit digits for IQ2_XXS/IQ1_S/IQ2_XS/IQ2_S, four",
        "3-bit digits for IQ3_XXS/IQ3_S.",
        '"""',
        "",
    ]
    for name in RENDER_ORDER:
        values = tables[name]
        lines.append(f"comptime {name}_GRID = SIMD[DType.uint16, {len(values)}](")
        for offset in range(0, len(values), 12):
            row = ", ".join(f"0x{value:04X}" for value in values[offset : offset + 12])
            lines.append(f"    {row},")
        lines.extend((")", ""))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path, help="path to llama.cpp gguf-py/gguf/quants.py")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("aesir_engine/core/iq_codebooks.mojo"),
    )
    args = parser.parse_args()
    args.output.write_text(render(extract_tables(args.source)), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
