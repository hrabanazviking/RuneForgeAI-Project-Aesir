#!/usr/bin/env python3
"""A-055 SPIR-V build pipeline for Project Aesir (Wave 7).

Compiles every GLSL compute kernel in aesir_engine/shaders/*.comp to
SPIR-V at BUILD TIME with glslangValidator, validates each module with
spirv-val, and emits the versioned in-repo artefacts the engine
consumes:

  aesir_engine/shaders/generated/<name>.spv          (build artefact)
  aesir_engine/shaders/generated/aesir_shaders_spv.h (embedded words)
  aesir_engine/shaders/SHADER_MANIFEST.json          (hashes recorded)

Nothing is fetched at runtime or at build time: the only inputs are
the .comp sources in this repository and the host's glslang /
SPIRV-Tools install, both checked fail-closed before any compile.
Compilation is proven deterministic per kernel (compiled twice, byte
compared) before its hash is recorded.

Usage:
  scripts/build_shaders.py           regenerate artefacts in-repo
  scripts/build_shaders.py --check   regenerate to a temp dir and
                                     verify the in-repo artefacts
                                     match byte-for-byte (clean
                                     checkout verification)
"""
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADER_DIR = ROOT / "aesir_engine" / "shaders"
GEN_DIR = SHADER_DIR / "generated"
MANIFEST_PATH = SHADER_DIR / "SHADER_MANIFEST.json"
HEADER_PATH = GEN_DIR / "aesir_shaders_spv.h"
TARGET_ENV = "vulkan1.0"
# A-074: per-kernel target-env overrides. Only kernels whose GLSL
# needs a newer SPIR-V level opt in (subgroup arithmetic requires
# SPIR-V 1.3, i.e. --target-env vulkan1.1); every other kernel stays
# (softmax was tried and reverted in A-074: its subgroup reduction
# measured noise-level through the per-dispatch pipeline path -
# honest negative, numbers in hidden_files/A074_LEDGER.md);
# at the default so its SPIR-V stays byte-identical to the banked
# A-055 artefacts. The manifest records "target_env" per kernel
# ONLY for overridden kernels, so unchanged kernels' manifest
# records stay byte-identical too.
TARGET_ENV_OVERRIDES = {
    "attention_decode": "vulkan1.1",
    "attention_decode_strided": "vulkan1.1",
    "attention_prefill": "vulkan1.1",
}
SLICE = "A-055"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def tool_version(tool: str) -> str:
    out = subprocess.run(
        [tool, "--version"], capture_output=True, text=True, check=True
    )
    return out.stdout.strip().splitlines()[0].strip()


def compile_kernel(glslang: str, spirv_val: str, src: Path, out_dir: Path):
    """Compile one kernel twice; return its manifest record."""
    name = src.stem
    target_env = TARGET_ENV_OVERRIDES.get(name, TARGET_ENV)
    spv_paths = []
    for attempt in (1, 2):
        spv = out_dir / f"{name}.{attempt}.spv"
        subprocess.run(
            [
                glslang,
                "-V",
                "--target-env",
                target_env,
                str(src),
                "-o",
                str(spv),
            ],
            capture_output=True,
            text=True,
            check=True,
        )
        subprocess.run(
            [spirv_val, "--target-env", target_env, str(spv)],
            capture_output=True,
            text=True,
            check=True,
        )
        spv_paths.append(spv)
    first = spv_paths[0].read_bytes()
    second = spv_paths[1].read_bytes()
    if first != second:
        raise SystemExit(f"FAIL: {name}: glslang output is not deterministic")
    if len(first) % 4 != 0:
        raise SystemExit(f"FAIL: {name}: SPIR-V size not word-aligned")
    words = [
        int.from_bytes(first[i : i + 4], "little")
        for i in range(0, len(first), 4)
    ]
    if not words or words[0] != 0x07230203:
        raise SystemExit(f"FAIL: {name}: bad SPIR-V magic word")
    record_extra = {}
    if target_env != TARGET_ENV:
        record_extra["target_env"] = target_env
    return {
        **record_extra,
        "name": name,
        "source": f"aesir_engine/shaders/{src.name}",
        "source_sha256": sha256(src.read_bytes()),
        "spv_sha256": sha256(first),
        "spv_bytes": len(first),
        "spv_words": len(words),
        "spirv_version_word": words[1],
        "_spv": first,
        "_words": words,
    }


def render_header(records) -> str:
    lines = [
        "/* aesir_shaders_spv.h -- GENERATED by scripts/build_shaders.py",
        " * (slice A-055 SPIR-V build pipeline). Do not edit by hand:",
        " * regenerate with `python3 scripts/build_shaders.py`.",
        " * Every array below is the verbatim glslangValidator output for",
        " * the named .comp source in aesir_engine/shaders/; hashes are",
        " * recorded in aesir_engine/shaders/SHADER_MANIFEST.json. */",
        "#ifndef AESIR_SHADERS_SPV_H",
        "#define AESIR_SHADERS_SPV_H",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    for rec in records:
        const = "k" + "".join(p.capitalize() for p in rec["name"].split("_")) + "Spv"
        rec["_const"] = const
        lines.append(
            f"/* {rec['name']}.comp -> SPIR-V, {rec['spv_bytes']} bytes, "
            f"sha256 {rec['spv_sha256']} */"
        )
        lines.append(f"static const uint32_t {const}[] = {{")
        words = rec["_words"]
        for i in range(0, len(words), 4):
            chunk = ", ".join(f"0x{w:08x}u" for w in words[i : i + 4])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append(f"static const size_t {const}Bytes = sizeof({const});")
        lines.append("")
    lines.append("typedef struct { const char *name; const uint32_t *words; size_t bytes; const char *sha256; } AesirShaderEntry;")
    lines.append("static const AesirShaderEntry kAesirShaders[] = {")
    for rec in records:
        lines.append(
            f'    {{ "{rec["name"]}", {rec["_const"]}, {rec["_const"]}Bytes, '
            f'"{rec["spv_sha256"]}" }},'
        )
    lines.append("};")
    lines.append(
        "static const size_t kAesirShaderCount = "
        "sizeof(kAesirShaders) / sizeof(kAesirShaders[0]);"
    )
    lines.append("")
    lines.append("#endif /* AESIR_SHADERS_SPV_H */")
    lines.append("")
    return "\n".join(lines)


def build(out_root: Path):
    glslang = shutil.which("glslangValidator")
    spirv_val = shutil.which("spirv-val")
    if not glslang or not spirv_val:
        raise SystemExit(
            "FAIL: glslangValidator and spirv-val are required on the "
            "host (build-time tools; nothing is fetched)"
        )
    sources = sorted(SHADER_DIR.glob("*.comp"))
    if not sources:
        raise SystemExit("FAIL: no .comp kernels in aesir_engine/shaders/")
    gen_dir = out_root / "generated"
    gen_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        records = [
            compile_kernel(glslang, spirv_val, src, Path(tmp)) for src in sources
        ]
    for rec in records:
        (gen_dir / f"{rec['name']}.spv").write_bytes(rec["_spv"])
    header = render_header(records)
    (gen_dir / "aesir_shaders_spv.h").write_text(header)
    manifest = {
        "schema": 1,
        "slice": SLICE,
        "target_env": TARGET_ENV,
        "glslang": tool_version(glslang),
        "spirv_val": tool_version(spirv_val),
        "deterministic": True,
        "kernel_count": len(records),
        "kernels": [
            {k: v for k, v in rec.items() if not k.startswith("_")}
            for rec in records
        ],
    }
    manifest_text = json.dumps(manifest, indent=2) + "\n"
    (out_root / "SHADER_MANIFEST.json").write_text(manifest_text)
    return manifest


def main() -> int:
    check = "--check" in sys.argv[1:]
    if check:
        with tempfile.TemporaryDirectory() as tmp:
            staging = Path(tmp) / "shaders"
            staging.mkdir(parents=True)
            build(staging)
            for rel in (
                "SHADER_MANIFEST.json",
                "generated/aesir_shaders_spv.h",
            ):
                want = (SHADER_DIR / rel).read_bytes()
                got = (staging / rel).read_bytes()
                if want != got:
                    print(f"CHECK FAIL: {rel} is stale; run build_shaders.py")
                    return 1
            manifest = json.loads((SHADER_DIR / "SHADER_MANIFEST.json").read_text())
            for kern in manifest["kernels"]:
                spv = GEN_DIR / f"{kern['name']}.spv"
                if not spv.exists() or sha256(spv.read_bytes()) != kern["spv_sha256"]:
                    print(f"CHECK FAIL: generated/{kern['name']}.spv hash mismatch")
                    return 1
        print(
            f"CHECK PASS: {manifest['kernel_count']} kernels, in-repo "
            "artefacts match a fresh build"
        )
        return 0
    manifest = build(SHADER_DIR)
    for kern in manifest["kernels"]:
        print(
            f"BUILT {kern['name']}: {kern['spv_bytes']} bytes "
            f"sha256 {kern['spv_sha256']}"
        )
    print(f"MANIFEST: {manifest['kernel_count']} kernels -> {MANIFEST_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
